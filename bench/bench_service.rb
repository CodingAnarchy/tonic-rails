# frozen_string_literal: true

# Benchmark service with realistic Rails-like handlers.
#
# Handler complexity tiers:
#   HealthCheck — trivial (baseline dispatch overhead)
#   GetProduct   — single "DB lookup" + object construction
#   ListProducts — repeated object construction + filtering
#   CreateProduct — validation + "DB write" + object construction
#   BatchGetProducts — N lookups + not-found tracking
#
# Each handler simulates I/O via sleep to model DB latency.
# The SIMULATED_DB_LATENCY_MS env var controls the sleep duration.
#
# Run:
#   ruby -Ibench -e 'require_relative "bench_service"; Tonic::Rails.server.start'

require "tonic-rails"
require_relative "shop_pb"  # generated by: protoc --ruby_out=bench -Ibench shop.proto
require "json"
require "logger"

# Simulated database — a hash keyed by product ID.
# Pre-populated with 1000 products so lookups are realistic.
class SimulatedDB
  def initialize(count: 1000)
    @data = {}
    count.times do |i|
      @data[i + 1] = {
        "id" => i + 1,
        "title" => "Product #{i + 1}",
        "description" => "A fine product with description #{i + 1}. " + ("lorem ipsum dolor sit amet. " * 3),
        "price_cents" => (rand * 10000).to_i + 100,
        "currency" => "USD",
        "tags" => ["featured", "new", "sale"].sample(rand(1..3)),
        "status" => [1, 2, 2, 2, 3].sample,  # weighted toward ACTIVE
        "created_at_unix" => 1700000000 + i * 3600,
        "updated_at_unix" => 1700000000 + i * 3600 + 1800,
      }
    end
  end

  def find(id)
    @data[id]
  end

  def all(limit:, offset:, tag_filter: nil)
    results = @data.values
    if tag_filter
      results = results.select { |p| p["tags"]&.include?(tag_filter) }
    end
    total = results.size
    results = results[offset, limit] || []
    [results, total]
  end

  def insert(product)
    id = @data.keys.max + 1
    product["id"] = id
    product["created_at_unix"] = Time.now.to_i
    product["updated_at_unix"] = Time.now.to_i
    @data[id] = product
    product
  end

  def count
    @data.size
  end
end

class ProductService
  include Tonic::Rails::Base

  service "shop.ProductService"

  rpc :GetProduct, Shop::GetProductRequest, Shop::Product
  rpc :ListProducts, Shop::ListProductsRequest, Shop::ListProductsResponse
  rpc :CreateProduct, Shop::CreateProductRequest, Shop::Product
  rpc :BatchGetProducts, Shop::BatchGetProductsRequest, Shop::BatchGetProductsResponse
  rpc :HealthCheck, Shop::HealthCheckRequest, Shop::HealthCheckResponse
  rpc :GetProductDetail, Shop::GetProductDetailRequest, Shop::GetProductDetailResponse
  rpc :SearchProducts, Shop::SearchProductsRequest, Shop::SearchProductsResponse
  rpc :CheckoutPreview, Shop::CheckoutPreviewRequest, Shop::CheckoutPreviewResponse
  rpc :Dashboard, Shop::DashboardRequest, Shop::DashboardResponse

  DB_LATENCY_MS = ENV.fetch("SIMULATED_DB_LATENCY_MS", "2").to_i

  def initialize
    @db = self.class.instance_variable_get(:@db) || self.class.setup_db
  end

  def self.setup_db
    @db = SimulatedDB.new
  end

  # ── Handlers (always receive Hash, return Hash) ──────────────────

  def get_product(request)
    # Simulate DB lookup latency
    sleep_db

    product = @db.find(request["id"])
    unless product
      raise Tonic::Rails::RpcError.new("product #{request['id']} not found", code: :not_found)
    end

    # Simulate JSON serialization (common in Rails for cache fragments)
    _json = JSON.generate(product)

    product
  end

  def list_products(request)
    sleep_db

    limit = request["limit"] || 20
    offset = request["offset"] || 0
    tag_filter = request["tag_filter"]

    products, total = @db.all(limit: limit, offset: offset, tag_filter: tag_filter)

    # Simulate view rendering (string concatenation + JSON)
    _render = products.map { |p| JSON.generate(p) }.join(",")

    {
      "products" => products,
      "total" => total,
    }
  end

  def create_product(request)
    # Validation (typical Rails controller pattern)
    if request["title"].nil? || request["title"].to_s.strip.empty?
      raise Tonic::Rails::RpcError.new("title is required", code: :invalid_argument)
    end
    if request["price_cents"].nil? || request["price_cents"].to_i <= 0
      raise Tonic::Rails::RpcError.new("price_cents must be positive", code: :invalid_argument)
    end

    sleep_db  # simulate DB write (slightly longer)

    product = {
      "title" => request["title"],
      "description" => request["description"] || "",
      "price_cents" => request["price_cents"],
      "currency" => request["currency"] || "USD",
      "tags" => request["tags"] || [],
      "status" => 1,  # DRAFT
    }

    @db.insert(product)
  end

  def batch_get_products(request)
    ids = request["ids"] || []
    sleep_db

    products = []
    not_found = []

    ids.each do |id|
      product = @db.find(id)
      if product
        products << product
      else
        not_found << id
      end
    end

    {
      "products" => products,
      "not_found_ids" => not_found,
    }
  end

  # ── Realistic multi-query handlers ──────────────────────────────

  # "Show page" pattern: 3 sequential DB queries + CPU serialization.
  # Simulates: find product (5ms) → load reviews (10ms) → load related (8ms)
  def get_product_detail(request)
    # Query 1: find product
    sleep_real(5)
    product = @db.find(request["id"])
    raise Tonic::Rails::RpcError.new("not found", code: :not_found) unless product

    # CPU: cache fragment serialization (typical Rails view caching)
    _cache_fragment = JSON.generate(product)

    # Query 2: load reviews
    sleep_real(10)
    reviews = (1..5).map do |i|
      { "id" => i, "product_id" => product["id"], "rating" => 4 + (i % 2),
        "author" => "user#{i}", "body" => "Review #{i} for #{product['title']}",
        "created_at_unix" => 1700000000 + i * 86400 }
    end

    # Query 3: load related products
    sleep_real(8)
    related = (1..4).map do |i|
      @db.find(product["id"].to_i + i + 1) || @db.find(i + 1)
    end.compact

    # CPU: build response with JSON fragment caching
    _review_json = reviews.map { |r| JSON.generate(r) }

    { "product" => product, "reviews" => reviews, "related_products" => related }
  end

  # "Search" pattern: 1 slow query + CPU facets + 1 secondary query.
  # Simulates: full-text search (25ms) → process results → load tags (5ms)
  def search_products(request)
    limit = request["limit"] || 20
    offset = request["offset"] || 0
    min_price = request["min_price_cents"] || 0
    max_price = request["max_price_cents"] || 1_000_000
    tag_filter = request["tag_filter"]

    # Query 1: slow search (25ms — aggregates + full-text scan)
    sleep_real(25)
    products, total = @db.all(limit: limit, offset: offset, tag_filter: tag_filter)

    # CPU: filter by price range, build facets
    filtered = products.select do |p|
      price = p["price_cents"].to_i
      price >= min_price && price <= max_price
    end
    _facets = filtered.group_by { |p| p["tags"]&.first || "none" }
                      .transform_values(&:size)

    # Query 2: load tag associations (5ms)
    sleep_real(5)
    _tag_json = filtered.map { |p| JSON.generate(p["tags"] || []) }

    { "products" => filtered, "total" => total, "query_time_ms" => 30 }
  end

  # "Checkout" pattern: 4 sequential DB queries + price calculation.
  # Simulates: load cart (3ms) → validate inventory (15ms) → shipping (8ms) → user prefs (5ms)
  def checkout_preview(request)
    cart_items = request["cart_items"] || []
    raise Tonic::Rails::RpcError.new("empty cart", code: :invalid_argument) if cart_items.empty?

    # Query 1: load cart (3ms)
    sleep_real(3)

    # Query 2: validate inventory per item (15ms — batch check)
    sleep_real(15)
    items = cart_items.map do |ci|
      product = @db.find(ci["product_id"])
      raise Tonic::Rails::RpcError.new("product #{ci['product_id']} not found", code: :not_found) unless product
      qty = ci["quantity"].to_i
      unit = product["price_cents"].to_i
      { "product" => product, "quantity" => qty,
        "unit_price_cents" => unit, "line_total_cents" => unit * qty }
    end

    # CPU: calculate subtotal
    subtotal = items.sum { |i| i["line_total_cents"].to_i }

    # Query 3: calculate shipping (8ms)
    sleep_real(8)
    shipping = subtotal > 5000 ? 0 : 599

    # Query 4: load user preferences for tax rate (5ms)
    sleep_real(5)
    tax = (subtotal * 0.085).to_i

    { "items" => items, "subtotal_cents" => subtotal,
      "shipping_cents" => shipping, "tax_cents" => tax,
      "total_cents" => subtotal + shipping + tax }
  end

  # "Dashboard" pattern: 3 slow aggregate queries + stat aggregation.
  # Simulates: recent orders (25ms) → revenue stats (20ms) → product count (10ms)
  def dashboard(_request)
    # Query 1: recent orders aggregate (25ms — GROUP BY date, ORDER BY)
    sleep_real(25)
    total_orders = 15_382
    total_revenue = 2_847_293_00

    # CPU: aggregate stats
    avg_order = total_revenue / [total_orders, 1].max
    _stats_json = JSON.generate({ "orders" => total_orders, "revenue" => total_revenue })

    # Query 2: revenue stats (20ms — SUM + window functions)
    sleep_real(20)

    # Query 3: product count by status (10ms)
    sleep_real(10)
    _, active_count = @db.all(limit: 1, offset: 0, tag_filter: nil)

    # CPU: build top products list
    top, _ = @db.all(limit: 5, offset: 0, tag_filter: nil)
    _top_json = top.map { |p| JSON.generate(p) }

    { "total_orders" => total_orders, "total_revenue_cents" => total_revenue,
      "avg_order_value_cents" => avg_order, "recent_product_count" => @db.count,
      "active_product_count" => active_count, "top_products" => top }
  end

  def health_check(_request)
    {
      "healthy" => true,
      "service" => "product-service",
    }
  end

  private

  def sleep_db
    return if DB_LATENCY_MS.zero?

    # Simulate DB I/O — releases GVL during sleep
    sleep(DB_LATENCY_MS / 1000.0)
  end

  def sleep_real(ms)
    sleep(ms / 1000.0)
  end
end

# ── Gem configuration ──────────────────────────────────────────────

ProductService.setup_db  # pre-populate the DB

Tonic::Rails.configure do |config|
  config.bind_address = ENV.fetch("TONIC_RAILS_BIND", "0.0.0.0:50051")
  config.max_message_size = 4 * 1024 * 1024
  config.dispatch_threads = ENV.fetch("TONIC_RAILS_DISPATCH_THREADS", "4").to_i
  config.logger = Logger.new($stderr)
end


Tonic::Rails.server.register(ProductService)

