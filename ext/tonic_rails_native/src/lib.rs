//! tonic-rails native extension
//!
//! Bridges Ruby (via Magnus) to a tonic-based gRPC transport layer.
//!
//! # Architecture
//!
//! ```text
//!  Ruby thread (holds GVL)            Tokio runtime (no GVL)
//!  ───────────────────────            ────────────────────────
//!  Native::Server.new(addr)     ──►   tokio::Runtime created
//!  #on_request(proc)                  callback VALUE stored + GC-marked
//!  #start_server                ──►   tonic::transport::Server spawned
//!    broadcast::Receiver               (TLS, keepalive, compression built-in)
//!  #serve_worker                      per-request:
//!    rb_thread_call_without_gvl         generic tower::Service receives
//!                                       Request<Incoming> from tonic
//!                                       unframe → raw bytes
//!                                       crossbeam → Ruby worker
//!  ───────────────────────            ────────────────────────
//!  Ruby worker (GVL acquired)    ◄──► rb_thread_call_with_gvl
//!    callback.call(path, bytes,       frame response          ◄── bytes
//!    metadata)                        return Response<BoxBody>
//!  #stop_server                 ──►   broadcast signal → drain
//!                                     rt.shutdown_timeout
//! ```
//!
//! # Generic Service (raw-byte dispatch)
//!
//! Instead of implementing tonic-build's generated service traits (which
//! would add prost decode→encode→decode→encode per request), we register a
//! **generic tower::Service** that does raw-byte passthrough: tonic delivers
//! `http::Request<hyper::body::Incoming>`, we unframe the gRPC message, send
//! raw protobuf bytes to Ruby via the GVL bridge, and frame the response.
//!
//! Each service from the proto gets a `NamedService` wrapper (compile-time
//! `NAME` const) so tonic routes by path prefix.  `tonic-build` is used only
//! for `FILE_DESCRIPTOR_SET` (feeding tonic-reflection) — no typed traits.
//!
//! # GVL bridge
//! The critical coordination is the GVL (Global VM Lock).  The tonic server
//! runs on tokio worker threads that do NOT hold the GVL.  When a gRPC
//! request arrives, we must re-acquire the GVL to call the Ruby dispatch
//! callback.  This is done via `rb_thread_call_with_gvl`.
//!
//! Conversely, `#serve_worker` must RELEASE the GVL while waiting on the
//! dispatch channel so that Ruby can process callbacks on other threads.
//! This is done via `rb_thread_call_without_gvl`.
//!
//! # SO_REUSEPORT
//!
//! The listener sets SO_REUSEPORT so that multiple Puma/Unicorn worker
//! processes can each bind to the same port.  The kernel distributes
//! incoming TCP connections across all bound sockets round-robin, giving
//! N-way GVL parallelism (one GVL per worker process).

