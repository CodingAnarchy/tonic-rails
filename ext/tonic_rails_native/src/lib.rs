// ─── NativeServer (Magnus-wrapped Ruby class) ─────────────────────

/// Ruby class `TonicRails::Native::Server`.
///
///   .new(bind_address, max_message_size) → Server
///   #on_request(proc)                     → stores dispatch callback
///   #set_tls(cert_path, key_path)          → enable TLS
///   #start_server                          → creates tokio runtime + channels
///   #serve_worker                          → blocks, drains request channel
///   #stop_server                           → stops tokio runtime, cleanup
///   #shutdown                              → signals all workers to stop
///
/// Multi-threaded dispatch: the Ruby side creates N `Thread.new` threads,
/// each calling #serve_worker.  All workers share a single crossbeam
/// channel receiver (Receiver<Box<DispatchContext>> is Sync).  When one worker
/// is inside a handler (GVL held), others wait on the channel (GVL
/// released).  If the handler does blocking I/O (sleep, DB, HTTP — which
/// releases the GVL internally), another worker can acquire the GVL and
/// run its handler concurrently.
#[derive(magnus::TypedData)]
#[magnus(class = "TonicRails::Native::Server", mark)]
struct NativeServer {
    bind_address: String,
    max_message_size: usize,
    callback: Mutex<Option<Opaque<Value>>>,
    runtime: Mutex<Option<Runtime>>,
    /// Shared shutdown flag — all worker threads check this.
    shutdown_flag: Mutex<Option<Arc<AtomicBool>>>,
    /// Channel receiver — shared (via Arc) across all worker threads.
    request_rx: Mutex<Option<Arc<crossbeam_channel::Receiver<Box<DispatchContext>>>>>,
    /// Broadcast sender — triggers tonic graceful shutdown + drain timer.
    shutdown_tx: Mutex<Option<broadcast::Sender<()>>>,
    /// Optional TLS cert/key paths — passed to tonic ServerTlsConfig.
    tls_config: Mutex<Option<(String, String)>>,
    /// Graceful shutdown drain timeout in seconds.
    drain_timeout: Mutex<Duration>,
    /// Maximum number of concurrent TCP connections.
    max_connections: AtomicUsize,
    /// Max concurrent HTTP/2 streams per connection (DoS prevention).
    concurrency_limit_per_connection: AtomicUsize,
    /// Active connection counter (for observability/logging).
    active_connections: Arc<AtomicUsize>,
    /// Number of tokio worker threads (None = default = num CPUs).
    worker_threads: Mutex<Option<usize>>,
    /// HTTP/2 keepalive ping interval.
    keepalive_interval: Mutex<Duration>,
    /// HTTP/2 keepalive ping timeout (connection dropped if no pong).
    keepalive_timeout: Mutex<Duration>,
    /// Atomic request counters for observability.
    stats: Arc<ServerStats>,
    /// Enable gzip compression for responses, accept compressed requests.
    compression_enabled: Arc<AtomicBool>,
    /// Enable/disable gRPC reflection service (default: disabled).
    reflection_enabled: AtomicBool,
    /// Health reporter for flipping to NOT_SERVING during shutdown.
    health_reporter: Mutex<Option<tonic_health::server::HealthReporter>>,
}

impl NativeServer {
    fn new(bind_address: String, max_message_size: usize) -> Result<Self, Error> {
        Ok(Self {
            bind_address,
            max_message_size,
            callback: Mutex::new(None),
            runtime: Mutex::new(None),
            shutdown_flag: Mutex::new(None),
            request_rx: Mutex::new(None),
            shutdown_tx: Mutex::new(None),
            tls_config: Mutex::new(None),
            drain_timeout: Mutex::new(Duration::from_secs(10)),
            max_connections: AtomicUsize::new(64),
            concurrency_limit_per_connection: AtomicUsize::new(32),
            active_connections: Arc::new(AtomicUsize::new(0)),
            worker_threads: Mutex::new(None),
            keepalive_interval: Mutex::new(Duration::from_secs(15)),
            keepalive_timeout: Mutex::new(Duration::from_secs(5)),
            compression_enabled: Arc::new(AtomicBool::new(false)),
            reflection_enabled: AtomicBool::new(false),
            stats: Arc::new(ServerStats::new()),
            health_reporter: Mutex::new(None),
        })
    }

    /// Store the Ruby dispatch callback (a Proc or any object responding to #call).
    ///
    /// Called from Ruby as:
    ///   server.on_request(proc { |path, bytes, metadata| ... })
    fn on_request(&self, callback: Value) -> Result<(), Error> {
        *self.callback.lock() = Some(callback.into());
        Ok(())
    }

    /// Enable TLS by specifying PEM-encoded certificate and key file paths.
    /// After calling this, all incoming connections are wrapped with TLS
    /// by tonic's transport layer.  ALPN "h2" is negotiated automatically.
    ///
    /// Called from Ruby as:
    ///   server.set_tls("/path/to/cert.pem", "/path/to/key.pem")
    fn set_tls(&self, cert_path: String, key_path: String) -> Result<(), Error> {
        let ruby = Ruby::get().expect("Ruby VM must be available for set_tls");

        if !std::path::Path::new(&cert_path).exists() {
            return Err(magnus::error::Error::new(
                ruby.exception_runtime_error(),
                format!("cert file not found: {cert_path}"),
            ));
        }
        if !std::path::Path::new(&key_path).exists() {
            return Err(magnus::error::Error::new(
                ruby.exception_runtime_error(),
                format!("key file not found: {key_path}"),
            ));
        }

        *self.tls_config.lock() = Some((cert_path, key_path));
        Ok(())
    }

    /// Set the graceful shutdown drain timeout in seconds.
    /// During shutdown, the server waits this long for active
    /// connections to finish in-flight requests before force-closing.
    ///
    /// Called from Ruby as:
    ///   server.set_drain_timeout(10)
    fn set_drain_timeout(&self, secs: u64) -> Result<(), Error> {
        *self.drain_timeout.lock() = Duration::from_secs(secs);
        Ok(())
    }

    /// Set the maximum number of concurrent TCP connections.
    /// New connections exceeding this limit are dropped.
    ///
    /// Called from Ruby as:
    ///   server.set_max_connections(64)
    fn set_max_connections(&self, max: usize) -> Result<(), Error> {
        self.max_connections.store(max, Ordering::Relaxed);
        Ok(())
    }

    /// Set the maximum number of concurrent HTTP/2 streams per
    /// connection.  Prevents a single client from exhausting the
    /// dispatch queue with many concurrent requests.
    ///
    /// Called from Ruby as:
    ///   server.set_concurrency_limit_per_connection(32)
    fn set_concurrency_limit_per_connection(&self, limit: usize) -> Result<(), Error> {
        self.concurrency_limit_per_connection
            .store(limit, Ordering::Relaxed);
        Ok(())
    }

    /// Set the number of tokio worker threads for the transport layer.
    /// None (default) uses the number of CPU cores.
    ///
    /// Called from Ruby as:
    ///   server.set_worker_threads(4)
    fn set_worker_threads(&self, n: usize) -> Result<(), Error> {
        *self.worker_threads.lock() = Some(n);
        Ok(())
    }

    /// Set HTTP/2 keepalive ping interval and timeout in seconds.
    /// A ping is sent every `interval` seconds; if no pong is received
    /// within `timeout` seconds, the connection is dropped.
    ///
    /// Called from Ruby as:
    ///   server.set_keepalive(15, 5)
    fn set_keepalive(&self, interval_secs: u64, timeout_secs: u64) -> Result<(), Error> {
        *self.keepalive_interval.lock() = Duration::from_secs(interval_secs);
        *self.keepalive_timeout.lock() = Duration::from_secs(timeout_secs);
        Ok(())
    }

    /// Enable or disable per-request logging (including OK responses).
    /// Errors are always logged regardless.  Default: false.
    ///   server.set_log_requests(true)
    fn set_log_requests(&self, enabled: bool) -> Result<(), Error> {
        self.stats.log_requests.store(enabled, Ordering::Relaxed);
        Ok(())
    }

    /// Enable or disable gzip compression for gRPC responses.
    /// When enabled, the server accepts gzip-compressed requests and
    /// sends gzip-compressed responses.
    ///
    /// Called from Ruby as:
    ///   server.set_compression(true)
    fn set_compression(&self, enabled: bool) -> Result<(), Error> {
        self.compression_enabled.store(enabled, Ordering::Relaxed);
        Ok(())
    }

    /// Enable or disable gRPC reflection service.
    /// When disabled, the reflection service is not added to the server.
    /// Should be disabled in production to avoid exposing API schema.
    ///
    /// Called from Ruby as:
    ///   server.set_reflection(false)
    fn set_reflection(&self, enabled: bool) -> Result<(), Error> {
        self.reflection_enabled.store(enabled, Ordering::Relaxed);
        Ok(())
    }

    /// Flip the health check status to NOT_SERVING for all registered
    /// services.  Called during graceful shutdown so load balancers
    /// stop sending traffic before connections are drained.
    ///
    /// Called from Ruby as:
    ///   server.set_not_serving
    fn set_not_serving(&self) -> Result<(), Error> {
        if let Some(reporter) = self.health_reporter.lock().as_mut() {
            if let Some(runtime) = self.runtime.lock().as_ref() {
                runtime.block_on(set_all_not_serving(reporter));
            }
        }
        Ok(())
    }

    /// Create the tokio runtime, dispatch channel, and shutdown signal.
    /// Called once before spawning worker threads.  Returns immediately.
    ///
    /// Called from Ruby as:
    ///   server.start_server
    fn start_server(&self) -> Result<(), Error> {
        let ruby = Ruby::get().expect("Ruby VM must be available when #start_server is called");

        let callback = (*self.callback.lock()).ok_or_else(|| {
            magnus::error::Error::new(
                ruby.exception_runtime_error(),
                "no dispatch callback set — call #on_request first",
            )
        })?;

        let addr: SocketAddr = self.bind_address.parse().map_err(|e| {
            magnus::error::Error::new(
                ruby.exception_arg_error(),
                format!("invalid bind address '{}': {e}", self.bind_address),
            )
        })?;

        let mut runtime_builder = tokio::runtime::Builder::new_multi_thread();
        runtime_builder.enable_all();
        if let Some(n) = *self.worker_threads.lock() {
            runtime_builder.worker_threads(n);
        }
        let runtime = runtime_builder.build().map_err(|e| {
            magnus::error::Error::new(
                ruby.exception_runtime_error(),
                format!("failed to create tokio runtime: {e}"),
            )
        })?;

        // Dispatch channel: tokio sends requests, Ruby worker threads
        // (inside rb_thread_call_without_gvl) receive and process them.
        let (request_tx, request_rx) = crossbeam_channel::bounded::<Box<DispatchContext>>(128);
        let request_rx = Arc::new(request_rx);

        // Shared shutdown flag — all workers check this.
        let shutdown_flag = Arc::new(AtomicBool::new(false));

        // Broadcast channel for tonic graceful shutdown + drain timer.
        // Two receivers: one for serve_with_incoming_shutdown, one for
        // the drain timeout.  When stop_server sends (), both fire:
        //   - serve stops accepting, starts draining in-flight connections
        //   - drain timer starts counting (drain_timeout + 2s)
        // select! completes when whichever finishes first.
        let (shutdown_tx, mut shutdown_rx1) = broadcast::channel::<()>(1);
        let mut shutdown_rx2 = shutdown_tx.subscribe();

        // Build the shared dispatch inner.
        let dispatch_inner = Arc::new(GrpcDispatchInner {
            callback: Arc::new(callback),
            request_tx,
            stats: self.stats.clone(),
            max_message_size: self.max_message_size,
            compression_enabled: self.compression_enabled.clone(),
        });
        let listener = {
            let _enter = runtime.enter();
            let domain = if addr.is_ipv4() {
                Domain::IPV4
            } else {
                Domain::IPV6
            };
            let socket = Socket::new(domain, Type::STREAM, Some(Protocol::TCP)).map_err(|e| {
                magnus::error::Error::new(
                    ruby.exception_runtime_error(),
                    format!("failed to create socket: {e}"),
                )
            })?;
            let _ = socket.set_reuse_address(true);
            let _ = socket.set_reuse_port(true);
            let _ = socket.set_nonblocking(true);
            socket.bind(&addr.into()).map_err(|e| {
                magnus::error::Error::new(
                    ruby.exception_runtime_error(),
                    format!("failed to bind {addr}: {e}"),
                )
            })?;
            socket.listen(1024).map_err(|e| {
                magnus::error::Error::new(
                    ruby.exception_runtime_error(),
                    format!("failed to listen on {addr}: {e}"),
                )
            })?;
            TcpListener::from_std(std::net::TcpListener::from(socket)).map_err(|e| {
                magnus::error::Error::new(
                    ruby.exception_runtime_error(),
                    format!("failed to create tokio listener: {e}"),
                )
            })?
        };

        // Capture config for the async block.
        let drain = *self.drain_timeout.lock();
        let max_conns = self.max_connections.load(Ordering::Relaxed);
        let concurrency_limit = self
            .concurrency_limit_per_connection
            .load(Ordering::Relaxed);
        let keepalive_interval = *self.keepalive_interval.lock();
        let keepalive_timeout = *self.keepalive_timeout.lock();
        let tls = self.tls_config.lock().clone();
        let active_conns = self.active_connections.clone();
        let max_msg_size = self.max_message_size;

        // Create health reporter before spawn so we can store a clone
        // for set_not_serving during graceful shutdown.
        let (mut health_reporter, health_service) = tonic_health::server::health_reporter();
        runtime.block_on(set_all_serving(&mut health_reporter));
        *self.health_reporter.lock() = Some(health_reporter.clone());

        let reflection_enabled = self.reflection_enabled.load(Ordering::Relaxed);

        // Spawn the tonic server on the tokio runtime.
        runtime.spawn(async move {
            // ── Build tonic-reflection service ──────────────────────
            // Conditionally enabled via set_reflection(false) to avoid
            // exposing API schema in production. When disabled, an empty
            // reflection service is added (responds NOT_FOUND) to keep
            // the server type uniform.
            let reflection_service = if reflection_enabled {
                tonic_reflection::server::Builder::configure()
                    .register_encoded_file_descriptor_set(FILE_DESCRIPTOR_SET)
                    .register_encoded_file_descriptor_set(tonic_health::pb::FILE_DESCRIPTOR_SET)
                    .register_encoded_file_descriptor_set(
                        tonic_reflection::pb::v1::FILE_DESCRIPTOR_SET,
                    )
                    .build_v1()
                    .unwrap_or_else(|e| {
                        eprintln!("tonic-rails: failed to build reflection service: {e}");
                        tonic_reflection::server::Builder::configure()
                            .build_v1()
                            .expect("empty reflection builder should not fail")
                    })
            } else {
                tonic_reflection::server::Builder::configure()
                    .build_v1()
                    .expect("empty reflection builder should not fail")
            };
            // ── Build TLS config (if cert/key paths are set) ────────
            let tls_config = if let Some((cert_path, key_path)) = tls.as_ref() {
                match (std::fs::read(cert_path), std::fs::read(key_path)) {
                    (Ok(cert), Ok(key)) => {
                        let identity = tonic::transport::Identity::from_pem(cert, key);
                        Some(tonic::transport::ServerTlsConfig::new().identity(identity))
                    }
                    _ => {
                        eprintln!("tonic-rails: failed to read TLS cert/key files");
                        None
                    }
                }
            } else {
                eprintln!(
                    "tonic-rails: WARNING — starting without TLS; gRPC traffic will be plaintext"
                );
                None
            };

            // ── Build tonic server ──────────────────────────────────
            let build_server = || {
                tonic::transport::Server::builder()
                    .http2_keepalive_interval(Some(keepalive_interval))
                    .http2_keepalive_timeout(Some(keepalive_timeout))
                    .tcp_nodelay(true)
                    .tcp_keepalive(Some(Duration::from_secs(60)))
                    .concurrency_limit_per_connection(concurrency_limit)
                    .http2_max_header_list_size(16 * 1024)
                    .initial_stream_window_size(max_msg_size as u32)
            };

            let server = build_server();
            let mut server = if let Some(config) = tls_config {
                match server.tls_config(config) {
                    Ok(s) => s,
                    Err(e) => {
                        eprintln!(
                            "tonic-rails: TLS config failed: {e} — falling back to plaintext"
                        );
                        build_server()
                    }
                }
            } else {
                server
            };

            // ── Register services ───────────────────────────────────
            // Generated service wrappers are registered via the macro;
            // tonic-health and tonic-reflection are sibling services.
            let routes = register_dispatch_services!(server, dispatch_inner)
                .add_service(health_service)
                .add_service(reflection_service);

            // ── Serve with graceful shutdown + drain timeout ────────
            // Wrap the incoming stream with a semaphore-enforced
            // connection limit.  Each connection acquires a permit on
            // accept; the permit is held in PermitIo and released when
            // tonic drops the connection.  max_connections = 0 means
            // unlimited (clamped to Semaphore::MAX_PERMITS).
            let raw_incoming = tokio_stream::wrappers::TcpListenerStream::new(listener);
            let permits = if max_conns > 0 {
                max_conns
            } else {
                Semaphore::MAX_PERMITS
            };
            let semaphore = Arc::new(Semaphore::new(permits));
            let incoming = ConnectionLimitedStream {
                inner: raw_incoming,
                semaphore,
                active: active_conns,
            };

            // serve_with_incoming_shutdown: stops accepting when signal fires,
            // then drains in-flight connections (sends GOAWAY + waits).
            let serve_future = routes.serve_with_incoming_shutdown(incoming, async move {
                let _ = shutdown_rx1.recv().await;
            });

            // Drain timer: starts when shutdown signal fires, counts
            // drain_timeout + 2s.  If serve_future completes first
            // (graceful drain), select! returns.  If timer fires first
            // (drain takes too long), serve_future is dropped (force stop).
            let drain_future = async move {
                let _ = shutdown_rx2.recv().await;
                tokio::time::sleep(drain + Duration::from_secs(2)).await;
            };

            tokio::select! {
                _ = serve_future => {
                    eprintln!("tonic-rails: server stopped gracefully");
                }
                _ = drain_future => {
                    eprintln!("tonic-rails: drain timeout expired — force stopping");
                }
            }
        });

        // Store everything the workers and shutdown need.
        *self.runtime.lock() = Some(runtime);
        *self.shutdown_flag.lock() = Some(shutdown_flag);
        *self.request_rx.lock() = Some(request_rx);
        *self.shutdown_tx.lock() = Some(shutdown_tx);

        Ok(())
    }

    /// Run one dispatch worker loop.  Blocks until #shutdown is called
    /// or the channel is disconnected.  Called from Ruby threads:
    ///
    ///   threads = N.times.map { Thread.new { server.serve_worker } }
    ///   threads.each(&:join)
    ///
    /// Each worker calls rb_thread_call_without_gvl to release the GVL
    /// while waiting on the shared channel.  When a request arrives, one
    /// worker re-acquires the GVL via rb_thread_call_with_gvl and runs
    /// the handler.  Other workers continue waiting (GVL released).
    fn serve_worker(&self) -> Result<(), Error> {
        let request_rx = self.request_rx.lock().clone().ok_or_else(|| {
            let ruby = Ruby::get().expect("Ruby VM must be available");
            magnus::error::Error::new(
                ruby.exception_runtime_error(),
                "server not started — call #start_server first",
            )
        })?;
        let shutdown = self.shutdown_flag.lock().clone().ok_or_else(|| {
            let ruby = Ruby::get().expect("Ruby VM must be available");
            magnus::error::Error::new(
                ruby.exception_runtime_error(),
                "server not started — call #start_server first",
            )
        })?;

        let serve_ctx = ServeContext {
            shutdown: shutdown.clone(),
            request_rx,
        };
        let unblock_ctx = UnblockContext { shutdown };

        unsafe {
            rb_thread_call_without_gvl(
                Some(serve_blocking),
                &serve_ctx as *const _ as *mut c_void,
                Some(serve_unblock),
                &unblock_ctx as *const _ as *mut c_void,
            );
        }

        Ok(())
    }

    /// Stop the tokio runtime and clean up stored state.
    /// Called from Ruby after all worker threads have exited.
    ///
    /// Called from Ruby as:
    ///   server.stop_server
    fn stop_server(&self) -> Result<(), Error> {
        // Signal tonic to stop accepting + start draining.
        if let Some(tx) = self.shutdown_tx.lock().take() {
            let _ = tx.send(());
        }
        // Shut down the tokio runtime.  Use drain_timeout + 2s margin
        // so the runtime doesn't force-kill tasks before the drain
        // phase has a chance to complete gracefully.
        let drain = *self.drain_timeout.lock();
        let rt_timeout = drain + Duration::from_secs(2);
        if let Some(rt) = self.runtime.lock().take() {
            eprintln!("tonic-rails: stopping tokio runtime (timeout {rt_timeout:?})");
            rt.shutdown_timeout(rt_timeout);
            eprintln!("tonic-rails: tokio runtime stopped");
        }
        // Clean up stored state — dropping Arc<Receiver> disconnects
        // the channel, which drops any unprocessed dispatch contexts.
        *self.shutdown_flag.lock() = None;
        *self.request_rx.lock() = None;
        Ok(())
    }

    /// Signal all worker threads to stop.  Sets the shared shutdown flag;
    /// workers check it within 100ms (their recv_timeout interval) and
    /// break out of the serve loop.
    ///
    /// Called from Ruby as:
    ///   server.shutdown
    fn shutdown(&self) -> Result<(), Error> {
        if let Some(flag) = &*self.shutdown_flag.lock() {
            flag.store(true, Ordering::Relaxed);
        }
        Ok(())
    }

    /// Return current server stats as a Ruby Hash.
    ///
    /// Called from Ruby as:
    ///   server.stats  → { total:, successful:, errors:, deadline_exceeded:, resource_exhausted:, active_connections: }
    fn stats(&self) -> Result<RHash, Error> {
        let ruby = Ruby::get().expect("Ruby VM must be available for stats");
        let hash = ruby.hash_new();
        let _ = hash.aset(
            ruby.to_symbol("total"),
            self.stats.total_requests.load(Ordering::Relaxed),
        );
        let _ = hash.aset(
            ruby.to_symbol("successful"),
            self.stats.successful_requests.load(Ordering::Relaxed),
        );
        let _ = hash.aset(
            ruby.to_symbol("errors"),
            self.stats.error_requests.load(Ordering::Relaxed),
        );
        let _ = hash.aset(
            ruby.to_symbol("deadline_exceeded"),
            self.stats.deadline_exceeded.load(Ordering::Relaxed),
        );
        let _ = hash.aset(
            ruby.to_symbol("resource_exhausted"),
            self.stats.resource_exhausted.load(Ordering::Relaxed),
        );
        let _ = hash.aset(
            ruby.to_symbol("active_connections"),
            self.active_connections.load(Ordering::Relaxed),
        );
        Ok(hash)
    }
}

// GC mark: prevents Ruby from collecting the stored dispatch callback
// Proc while the Rust server holds a reference.  Wired via the `mark`
// flag on #[magnus(...)] above — Ruby's GC calls extern_mark which
// dispatches to this method.
impl DataTypeFunctions for NativeServer {
    fn mark(&self, marker: &gc::Marker) {
        if let Some(cb) = *self.callback.lock() {
            marker.mark(cb);
        }
    }
}

