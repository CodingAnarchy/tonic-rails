# frozen_string_literal: true

# Example gRPC service for a Rails application.
#
# This handler demonstrates realistic Rails patterns:
#   - "Database" access via a simulated in-memory store
#   - Validation with proper gRPC error codes
#   - JSON serialization (cache-fragment pattern)
#   - Batch operations with partial-failure tracking
#
# In a real app, the @db calls would be ActiveRecord queries,
# and the handler might use Rails helpers, mailers, or jobs.
#
# Run:  rails grpc:serve
# Test: grpcurl -plaintext -proto protos/shop.proto \
#         -d '{"id": 1}' 127.0.0.1:50052 shop.ProductService/GetProduct

require "tonic-rails"
require_relative "shop_pb"  # generated by: protoc --ruby_out=app/grpc -Iprotos protos/shop.proto
require "json"

# Simple in-memory "database" to simulate ActiveRecord without a real DB.
class ProductStore
  Product = Struct.new(:id, :title, :description, :price_cents, :currency,
                       :tags, :status, :created_at_unix, :updated_at_unix,
                       keyword_init: true) do
    def to_h
      super.transform_keys(&:to_s)
    end
  end

  def initialize
    @next_id = 1
    @data = {}
    10.times do |i|
      insert(Product.new(
        title: "Sample Product #{i + 1}",
        description: "A great product for demonstration purposes. " + ("Lorem ipsum dolor sit amet. " * 2),
        price_cents: (i + 1) * 1000 + 999,
        currency: "USD",
        tags: ["featured", "demo"].sample(rand(1..2)),
        status: 2,  # PRODUCT_STATUS_ACTIVE
      ))
    end
  end

  def find(id)
    @data[id]&.to_h
  end

  def all(limit:, offset:, tag_filter: nil)
    results = @data.values
    results = results.select { |p| p.tags&.include?(tag_filter) } if tag_filter
    total = results.size
    [results[offset, limit]&.map(&:to_h) || [], total]
  end

  def insert(product)
    id = @next_id
    @next_id += 1
    product.id = id
    product.created_at_unix = Time.now.to_i
    product.updated_at_unix = Time.now.to_i
    @data[id] = product
    product.to_h
  end
end

class ProductService
  include Tonic::Rails::Base

  service "shop.ProductService"

  rpc :GetProduct, Shop::GetProductRequest, Shop::Product
  rpc :ListProducts, Shop::ListProductsRequest, Shop::ListProductsResponse
  rpc :CreateProduct, Shop::CreateProductRequest, Shop::Product
  rpc :BatchGetProducts, Shop::BatchGetProductsRequest, Shop::BatchGetProductsResponse
  rpc :HealthCheck, Shop::HealthCheckRequest, Shop::HealthCheckResponse

  # Shared "database" across all handler instances.
  # In a real app, this would be ActiveRecord models.
  STORE = ProductStore.new

  # ── Handlers ──────────────────────────────────────────────────────
  # Each handler receives a Hash (string keys) and returns a Hash.
  # The gem handles protobuf ↔ Hash conversion:
  #   - prost-reflect mode: Rust does the conversion (no GVL)
  #   - raw-bytes mode:     Ruby does the conversion via google-protobuf

  def get_product(request)
    product = STORE.find(request["id"])
    raise Tonic::Rails::RpcError.new("product #{request['id']} not found", code: :not_found) unless product

    # Simulate Rails cache-fragment JSON serialization
    Rails.cache.write("product:#{request['id']}", JSON.generate(product)) if defined?(Rails.cache)

    product
  end

  def list_products(request)
    limit = request["limit"] || 20
    offset = request["offset"] || 0
    tag_filter = request["tag_filter"]

    products, total = STORE.all(limit: limit, offset: offset, tag_filter: tag_filter)

    {
      "products" => products,
      "total" => total,
    }
  end

  def create_product(request)
    # Validation — typical Rails controller pattern
    if request["title"].to_s.strip.empty?
      raise Tonic::Rails::RpcError.new("title is required", code: :invalid_argument)
    end
    if request["price_cents"].to_i <= 0
      raise Tonic::Rails::RpcError.new("price_cents must be positive", code: :invalid_argument)
    end

    product = STORE.insert(ProductStore::Product.new(
      title: request["title"],
      description: request["description"] || "",
      price_cents: request["price_cents"],
      currency: request["currency"] || "USD",
      tags: request["tags"] || [],
      status: 1,  # DRAFT
    ))

    # In a real app, might enqueue a background job:
    #   Rails.logger.info("Product created: #{product['id']}")
    #   ProductMailer.creation_email(product).deliver_later

    product
  end

  def batch_get_products(request)
    ids = request["ids"] || []
    products = []
    not_found = []

    ids.each do |id|
      product = STORE.find(id)
      product ? products << product : not_found << id
    end

    {
      "products" => products,
      "not_found_ids" => not_found,
    }
  end

  def health_check(_request)
    {
      "healthy" => true,
      "service" => "example-product-service",
    }
  end
end
